-- Scenarios --------------------------------------------------------------------

CREATE TABLE scenario (
    id                         bigint PRIMARY KEY,
    active_background_audio_id bigint,
    author_id                  bigint,
    created_at                 timestamp(6) with time zone,
    description                varchar(500),
    language_id                varchar(255),
    latitude                   double precision,
    location_name              varchar(200),
    longitude                  double precision,
    parent_scenario_id         bigint,
    published_at               timestamp(6) with time zone,
    review_comment             varchar(255),
    review_status              varchar(255) NOT NULL
        CHECK (review_status IN ('NONE', 'PENDING', 'APPROVED', 'REJECTED')),
    reviewed_at                timestamp(6) with time zone,
    reviewed_by_id             bigint,
    storyboard_columns         integer      NOT NULL,
    storyboard_layout_mode     varchar(255) NOT NULL
        CHECK (storyboard_layout_mode IN ('PRESET', 'CUSTOM')),
    storyboard_preset          varchar(64)  NOT NULL,
    title                      varchar(255) NOT NULL,
    visibility_status          varchar(255) NOT NULL
        CHECK (visibility_status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT uk_scenario_author_language_title UNIQUE (author_id, language_id, title)
);

