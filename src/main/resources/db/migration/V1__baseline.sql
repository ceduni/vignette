-- Community (accreditations and discussions) -----------------------------------

CREATE TABLE community.accreditation_request (
    id                   bigint PRIMARY KEY,
    created_at           timestamp(6) with time zone NOT NULL,
    motivation           varchar(2000)               NOT NULL,
    permission_type      varchar(255)                NOT NULL CHECK (permission_type IN (
        'COMMUNITY_REVIEW', 'LANGUAGE_EDIT', 'SCENARIO_EDIT', 'SCENARIO_MODERATE')),
    requested_by_user_id bigint                      NOT NULL,
    review_note          varchar(1500),
    reviewed_at          timestamp(6) with time zone,
    reviewed_by_user_id  bigint,
    scope_type           varchar(255)                NOT NULL CHECK (scope_type IN (
        'GLOBAL', 'SCENARIO', 'LANGUAGE', 'LANGUAGE_FAMILY')),
    status               varchar(255)                NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    target_id            varchar(255)
);

CREATE TABLE community.community_accreditation (
    id                 bigint PRIMARY KEY,
    granted_at         timestamp(6) with time zone NOT NULL,
    granted_by_user_id bigint                      NOT NULL,
    note               varchar(1500),
    permission_type    varchar(255)                NOT NULL CHECK (permission_type IN (
        'COMMUNITY_REVIEW', 'LANGUAGE_EDIT', 'SCENARIO_EDIT', 'SCENARIO_MODERATE')),
    scope_type         varchar(255)                NOT NULL CHECK (scope_type IN (
        'GLOBAL', 'SCENARIO', 'LANGUAGE', 'LANGUAGE_FAMILY')),
    target_id          varchar(255),
    user_id            bigint                      NOT NULL
);

CREATE TABLE community.discussion_message (
    id                bigint PRIMARY KEY,
    author_id         bigint                      NOT NULL,
    content           varchar(4000)               NOT NULL,
    contribution_type varchar(255)                NOT NULL CHECK (contribution_type IN (
        'GENERAL', 'TRANSCRIPTION', 'TRANSLATION', 'GLOSS', 'INTERPRETATION')),
    created_at        timestamp(6) with time zone NOT NULL,
    parent_message_id bigint,
    target_id         varchar(255)                NOT NULL,
    target_type       varchar(255)                NOT NULL CHECK (target_type IN ('LANGUAGE', 'AUDIO', 'SCENARIO'))
);

-- Glottolog import pipeline ----------------------------------------------------

CREATE TABLE glottolog_admin_settings (
    id                  bigint PRIMARY KEY,
    auto_update_enabled boolean     NOT NULL,
    frequency_days      integer,
    notification_email  varchar(255),
    update_frequency    varchar(32) NOT NULL CHECK (update_frequency IN (
        'MANUAL', 'TWO_WEEKS', 'ONE_MONTH', 'THREE_MONTHS', 'SIX_MONTHS')),
    updated_at          timestamp(6) with time zone,
    updated_by_username varchar(255)
);

CREATE TABLE glottolog_pipeline_state (
    id                         bigint PRIMARY KEY,
    active_history_id          bigint,
    config_auto_update_enabled boolean,
    config_frequency_days      integer,
    config_observed_at         timestamp(6) with time zone,
    current_status             varchar(64) NOT NULL,
    last_check_at              timestamp(6) with time zone,
    last_detected_checksum     varchar(128),
    last_downloaded_checksum   varchar(128),
    last_error                 varchar(4000),
    last_imported_checksum     varchar(128),
    last_success_at            timestamp(6) with time zone,
    last_validated_checksum    varchar(128),
    lock_expires_at            timestamp(6) with time zone,
    lock_heartbeat_at          timestamp(6) with time zone,
    lock_owner                 varchar(255),
    next_retry_at              timestamp(6) with time zone,
    next_run_at                timestamp(6) with time zone,
    retry_count                integer     NOT NULL,
    status_message             varchar(2000),
    updated_at                 timestamp(6) with time zone
);

CREATE TABLE glottolog_update_history (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_count        bigint,
    download_duration_ms  bigint,
    error_message         varchar(4000),
    finished_at           timestamp(6) with time zone,
    glottolog_version     varchar(64),
    imported_checksum     varchar(128),
    inserted_count        integer,
    pipeline_status       varchar(64),
    remote_checksum       varchar(128),
    retry_count           integer,
    selected_rows         integer,
    source_rows           integer,
    started_at            timestamp(6) with time zone NOT NULL,
    status                varchar(32)                 NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    sync_duration_ms      bigint,
    trigger_type          varchar(32),
    triggered_by_username varchar(255)                NOT NULL,
    unchanged_count       integer,
    updated_count         integer,
    worker_id             varchar(255)
);

CREATE TABLE glottolog_update_request (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claimed_at            timestamp(6) with time zone,
    claimed_by            varchar(255),
    error_message         varchar(4000),
    finished_at           timestamp(6) with time zone,
    heartbeat_at          timestamp(6) with time zone,
    history_id            bigint,
    requested_at          timestamp(6) with time zone NOT NULL,
    requested_by_username varchar(255)                NOT NULL,
    started_at            timestamp(6) with time zone,
    status                varchar(32)                 NOT NULL CHECK (status IN (
        'PENDING', 'CLAIMED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'CANCELLED'))
);

CREATE TABLE glottolog_notification (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body            varchar(8000) NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    delivery_detail varchar(1000),
    delivery_status varchar(32)   NOT NULL,
    history_id      bigint,
    pipeline_status varchar(64),
    subject         varchar(500)  NOT NULL,
    to_email        varchar(255)  NOT NULL,
    trigger_type    varchar(32)
);
